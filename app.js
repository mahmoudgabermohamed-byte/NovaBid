// 3D Tilt Effect on Dashboard
const tiltDashboard = document.getElementById('tiltDashboard');
if (tiltDashboard) {
  window.addEventListener('pointermove', e => {
    if (window.innerWidth < 960) return;
    const rect = tiltDashboard.getBoundingClientRect();
    const x = (e.clientX - rect.left) / rect.width - 0.5;
    const y = (e.clientY - rect.top) / rect.height - 0.5;
    if (Math.abs(x) < 1 && Math.abs(y) < 1) {
      tiltDashboard.style.transform = `perspective(1400px) rotateX(${ -y * 12 }deg) rotateY(${ x * 14 }deg) translateY(-5px)`;
    }
  });
  window.addEventListener('pointerleave', () => {
    tiltDashboard.style.transform = 'perspective(1400px) rotateX(0deg) rotateY(0deg) translateY(0px)';
  });
}

